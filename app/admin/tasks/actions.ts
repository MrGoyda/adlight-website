/**
 * Списание расхода прямо из задачи (1-клик финансовая связка)
 */
export async function recordTaskExpense(data: {
  taskId: string;
  amount: number;
  accountId: string;
  categoryId?: string;
  description: string;
  leadId?: string | null;
}) {
  try {
    const { taskId, amount, accountId, categoryId, description, leadId } = data;
    if (!amount || amount <= 0) return { error: "Сумма должна быть больше нуля" };
    if (!accountId) return { error: "Выберите счет списания" };

    await prisma.$transaction(async (tx) => {
      // 1. Получаем счет
      const sourceAcc = await tx.financeAccount.findUnique({ where: { id: accountId } });
      if (!sourceAcc) throw new Error("Счет списания не найден");

      // 2. Создаем проводку в казначействе
      await tx.dbTransaction.create({
        data: {
          type: TransactionType.EXPENSE_COMPANY,
          amount,
          description: description.trim(),
          accountId: sourceAcc.id,
          categoryId: categoryId || null,
          leadId: leadId || null,
          transactionDate: new Date(),
        },
      });

      // 3. Уменьшаем баланс счета
      await tx.financeAccount.update({
        where: { id: sourceAcc.id },
        data: { balance: sourceAcc.balance - amount },
      });

      // 4. Синхронизируем старый cashbox
      const state = await tx.companyState.findUnique({ where: { id: "global" } });
      if (state) {
        await tx.companyState.update({
          where: { id: "global" },
          data: { cashbox: state.cashbox - amount },
        });
      }

      // 5. Фиксируем фактический расход в самой задаче
      const task = await tx.crmTask.findUnique({ where: { id: taskId } });
      if (task) {
        await tx.crmTask.update({
          where: { id: taskId },
          data: {
            actualCost: (task.actualCost || 0) + amount,
          },
        });
      }
    });

    revalidatePath("/admin/tasks");
    revalidatePath("/admin/finance");
    revalidatePath("/admin/leads");
    return { success: true };
  } catch (error: any) {
    console.error("Failed to record task expense:", error);
    return { error: error.message || "Не удалось списать расход" };
  }
}

/**
 * Авто-нарезка задач производственного цикла при смене статуса заказа
 */
export async function generateLeadPipelineTasks(leadId: string, targetStatus: LeadStatus) {
  try {
    const lead = await prisma.lead.findUnique({
      where: { id: leadId },
      include: {
        tasks: {
          select: { id: true, stage: true, isAutoGenerated: true },
        },
      },
    });

    if (!lead || !lead.autoTasksEnabled) {
      return { success: true, count: 0 };
    }

    const tasksToCreate: any[] = [];
    const now = new Date();

    // 1. Статус ESTIMATE (Замер и смета)
    if (targetStatus === LeadStatus.ESTIMATE) {
      const hasMeasurement = lead.tasks.some((t) => t.stage === TaskStage.MEASUREMENT);
      if (!hasMeasurement) {
        tasksToCreate.push({
          title: `📐 Выезд на замер: ${lead.name}`,
          description: `Адрес: ${lead.address || "Не указан"}\nКлиент: ${lead.name} (${lead.phone})\nЗадача: Лазерная рулетка, фото фасада, проверка 220V.`,
          stage: TaskStage.MEASUREMENT,
          priority: TaskPriority.HIGH,
          dueDate: lead.appointmentDate || new Date(now.getTime() + 24 * 3600 * 1000),
          assignee: lead.manager || PartnerName.ELISEY,
          leadId: lead.id,
          isAutoGenerated: true,
          subtasks: {
            create: [
              { title: "Сделать замер рулеткой (длина, высота, глубина)", order: 0 },
              { title: "Сфотографировать фасад и окружение объекта", order: 1 },
              { title: "Проверить подводку питания 220V и место для трансформатора", order: 2 },
            ],
          },
        });
      }
    }

    // 2. Статус PROCESSED (Предоплата / В производство)
    else if (targetStatus === LeadStatus.PROCESSED) {
      const hasProduction = lead.tasks.some((t) => t.stage === TaskStage.PRODUCTION || t.stage === TaskStage.SUPPLY);
      if (!hasProduction) {
        // Задача 1: Закупка
        tasksToCreate.push({
          title: `🛒 Снабжение: материалы для заказа «${lead.name}»`,
          description: "Закупка сырья по смете: акрил, пластик ПВХ, светодиодные модули 12V, блоки питания, клей Cosmofen.",
          stage: TaskStage.SUPPLY,
          priority: TaskPriority.URGENT,
          dueDate: new Date(now.getTime() + 24 * 3600 * 1000),
          assignee: PartnerName.ELISEY,
          leadId: lead.id,
          isAutoGenerated: true,
          subtasks: {
            create: [
              { title: "Заказать акрил и ПВХ необходимой толщины", order: 0 },
              { title: "Купить светодиодные модули 12V и блок питания", order: 1 },
              { title: "Проверить наличие виниловой пленки Oracal", order: 2 },
            ],
          },
        });

        // Задача 2: Фрезеровка цеха
        tasksToCreate.push({
          title: `⚙️ Раскрой и фрезеровка: «${lead.name}»`,
          description: "Подготовка ЧПУ программ, фрезеровка задников букв из ПВХ, лицевых панелей из молочного акрила.",
          stage: TaskStage.PRODUCTION,
          priority: TaskPriority.HIGH,
          dueDate: new Date(now.getTime() + 2 * 24 * 3600 * 1000),
          assignee: PartnerName.DANIIL,
          leadId: lead.id,
          isAutoGenerated: true,
          subtasks: {
            create: [
              { title: "Проверить макет в Corel/DXF на ошибки", order: 0 },
              { title: "Запустить фрезеровку лицевых панелей и задников", order: 1 },
            ],
          },
        });

        // Задача 3: Сборка и пайка
        tasksToCreate.push({
          title: `🔨 Сборка световых букв & LED: «${lead.name}»`,
          description: "Склейка бортов, пайка диодной ленты/модулей, герметизация и контрольный тест подсветки.",
          stage: TaskStage.ASSEMBLY,
          priority: TaskPriority.NORMAL,
          dueDate: new Date(now.getTime() + 3 * 24 * 3600 * 1000),
          assignee: PartnerName.DANIIL,
          leadId: lead.id,
          isAutoGenerated: true,
          subtasks: {
            create: [
              { title: "Склеить борта букв жидким акрилом / клеем", order: 0 },
              { title: "Установить светодиодные модули и спаять проводку", order: 1 },
              { title: "Тест 24ч под нагрузкой на стенде цеха", order: 2 },
            ],
          },
        });

        // Задача 4: Монтаж
        tasksToCreate.push({
          title: `🏗️ Монтаж вывески: «${lead.name}»`,
          description: `Адрес монтажа: ${lead.address || "Уточнить у клиента"}\nКонтакты: ${lead.phone}`,
          stage: TaskStage.INSTALLATION,
          priority: TaskPriority.HIGH,
          dueDate: lead.deadline || new Date(now.getTime() + 5 * 24 * 3600 * 1000),
          assignee: PartnerName.ELISEY,
          leadId: lead.id,
          isAutoGenerated: true,
          subtasks: {
            create: [
              { title: "Забронировать автовышку / проверить лестницы", order: 0 },
              { title: "Собрать монтажный ящик (дюбеля, анкера, крепеж)", order: 1 },
              { title: "Монтаж на фасаде и подключение к питанию 220V", order: 2 },
            ],
          },
        });
      }
    }

    // 3. Статус COMPLETED (Сдача и закрытие)
    else if (targetStatus === LeadStatus.COMPLETED) {
      const hasHandover = lead.tasks.some((t) => t.stage === TaskStage.HANDOVER);
      if (!hasHandover) {
        tasksToCreate.push({
          title: `🤝 Сдача объекта и акт: «${lead.name}»`,
          description: "Подписать накладную/акт выполненных работ, получить финальный расчет и сделать фото для портфолио.",
          stage: TaskStage.HANDOVER,
          priority: TaskPriority.NORMAL,
          dueDate: now,
          assignee: lead.manager || PartnerName.ELISEY,
          leadId: lead.id,
          isAutoGenerated: true,
          subtasks: {
            create: [
              { title: "Подписать закрывающий акт выполненных работ", order: 0 },
              { title: "Проверить поступление остатка оплаты", order: 1 },
              { title: "Сделать качественные фото светящейся вывески в сумерках", order: 2 },
            ],
          },
        });
      }
    }

    if (tasksToCreate.length > 0) {
      for (const t of tasksToCreate) {
        await prisma.crmTask.create({ data: t });
      }
      revalidatePath("/admin/tasks");
      revalidatePath("/admin/leads");
    }

    return { success: true, count: tasksToCreate.length };
  } catch (error: any) {
    console.error("Failed to generate lead pipeline tasks:", error);
    return { success: false, error: error.message };
  }
}
