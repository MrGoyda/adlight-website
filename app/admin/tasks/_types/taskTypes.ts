import { 
  TaskStatus, 
  TaskPriority, 
  TaskStage, 
  PartnerName 
} from "@prisma/client";

export type { TaskStatus, TaskPriority, TaskStage, PartnerName };

export interface CrmSubtaskItem {
  id: string;
  createdAt: string;
  title: string;
  isCompleted: boolean;
  order: number;
  taskId: string;
}

export interface CrmTaskItem {
  id: string;
  createdAt: string;
  updatedAt: string;
  title: string;
  description: string | null;
  status: TaskStatus;
  priority: TaskPriority;
  stage: TaskStage;
  dueDate: string | null;
  completedAt: string | null;
  assignee: PartnerName | null;
  leadId: string | null;
  isAutoGenerated: boolean;
  estimatedCost: number | null;
  actualCost: number | null;
  lead?: {
    id: string;
    name: string;
    phone: string;
    address?: string | null;
    appointmentDate?: string | null;
    deadline?: string | null;
  } | null;
  subtasks: CrmSubtaskItem[];
}

export type TasksViewMode = "AGENDA" | "KANBAN" | "CALENDAR";

export type TaskFilterAssignee = "ALL" | PartnerName | "UNASSIGNED";
export type TaskFilterStage = "ALL" | TaskStage;
export type TaskFilterStatus = "ALL" | TaskStatus;

export interface TaskQuickCreatePayload {
  title: string;
  description?: string;
  stage?: TaskStage;
  priority?: TaskPriority;
  dueDate?: string;
  assignee?: PartnerName | null;
  leadId?: string | null;
  estimatedCost?: number;
  subtaskTitles?: string[];
}

export type TaskActionResult<T = void> =
  | { success: true; data?: T; taskId?: string; count?: number }
  | { success: false; error: string };

