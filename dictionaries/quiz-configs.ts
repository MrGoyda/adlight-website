export const getQuizContextKey = (context?: string): string => {
  if (!context) return "general";
  
  switch (context) {
    case "volume-letters":
    case "face-lit":
    case "full-lit":
    case "back-lit":
    case "side-lit":
    case "combo-lit":
    case "flat-letters":
    case "retro-letters":
    case "rgb-letters":
    case "acrylic-letters":
    case "stainless-letters":
    case "foam-letters":
    case "liquid-acrylic":
      return "volume-letters";

    case "lightboxes":
    case "panel-brackets":
      return "lightboxes";

    case "neon":
    case "interior":
      return "neon";

    case "branding-cars":
    case "auto-branding":
      return "branding-cars";

    case "window-branding":
      return "window-branding";

    case "facade-decoration":
    case "entrance-groups":
      return "facade-decoration";

    case "roof-installations":
    case "pylons":
      return "roof-installations";

    case "led-screens":
      return "led-screens";

    case "navigation":
    case "banners-plates":
      return "navigation";

    case "architectural-lighting":
      return "architectural-lighting";

    case "exhibition-stands":
      return "exhibition-stands";

    case "signboard-repair":
      return "signboard-repair";

    default:
      return "general";
  }
};

